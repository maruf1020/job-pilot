async function main() {
  const { db } = await import('@/lib/db')
  const { fetchCompanyBoard } = await import('@/lib/sources/ats')
  const { atsBoardUrl } = await import('@/lib/sources/ats')
  const { discoverBoards, findBoard } = await import('@/lib/sponsors/boards')
  const { registeredSponsor } = await import('@/lib/sponsors/registers')
  const { normalizeCompany } = await import('@/lib/text')
  const { DEFAULT_SEARCH } = await import('@/lib/settings/schema')
  const { mapLimit } = await import('@/lib/utils/semaphore')
  const repairOnly = process.argv.includes('--repair')
  const ctx = { search: DEFAULT_SEARCH, env: {}, fetch: globalThis.fetch, log: () => undefined } as never

  if (!repairOnly) {
    let added = 0
    let updated = 0
    let dead = 0
    const results = await mapLimit(CANDIDATES, 4, async (c) => {
      const ref = { id: 'probe', name: c.name, atsType: c.ats, atsSlug: c.slug, knownSponsor: false }
      try {
        const r = await fetchCompanyBoard(ref, ctx, 365)
        return { c, jobs: r.jobs.length, ok: true }
      } catch {
        // The guessed slug is wrong: try the generic discovery before giving up.
        const hit = await findBoard(c.name, c.domain)
        return hit ? { c: { ...c, ats: hit.atsType, slug: hit.atsSlug }, jobs: 1, ok: true, guessed: true } : { c, jobs: 0, ok: false }
      }
    })
    for (const r of results) {
      if (!r.ok) {
        dead++
        console.log(`  x ${r.c.name}: no board found (${r.c.ats}/${r.c.slug})`)
        continue
      }
      const normalizedName = normalizeCompany(r.c.name) || r.c.name.toLowerCase()
      const sponsor = await registeredSponsor(normalizedName)
      const existing = await db.company.findUnique({ where: { normalizedName }, select: { id: true, atsType: true, knownSponsor: true } })
      // The curated list only holds employers known to hire internationally, so they count as sponsors even when not (yet) on a register.
      const data = { atsType: r.c.ats, atsSlug: r.c.slug, careersUrl: atsBoardUrl(r.c.ats, r.c.slug), domain: r.c.domain ?? null, countryCode: r.c.country, lastFetchError: null, knownSponsor: true, ...(sponsor ? { notes: `Sponsor register (${sponsor.country}): ${sponsor.source}` } : {}) }
      void existing?.knownSponsor
      if (existing) {
        await db.company.update({ where: { id: existing.id }, data })
        updated++
      } else {
        await db.company.create({ data: { name: r.c.name, normalizedName, ...data } })
        added++
      }
      console.log(`  ✓ ${r.c.name}: ${r.c.ats}/${r.c.slug}${'guessed' in r && r.guessed ? ' (found by discovery)' : ''}${r.jobs ? `, ${r.jobs} engineering roles` : ''}`)
    }
    console.log(`curated boards: ${added} added, ${updated} updated, ${dead} without a live board`)
  }

  const repair = await discoverBoards({ scope: 'failing', limit: 200, log: (m) => console.log('  repair:', m) })
  console.log(`failing boards: ${repair.checked} checked, ${repair.found} repaired, ${repair.cleared} removed`)
  await db.$disconnect()
}

main().catch((err) => {
  console.error(err)
  process.exit(1)
})

